// Generate migration 3 from the authoritative DDL; no hand-copied table definitions.
// Run: node src/store/schema/generate-projects.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { parseSchema } from '../../../scripts/split-schema.mjs'
const authority = new URL('../../../docs/schema-2026-11-14.sql', import.meta.url)
const text = readFileSync(authority, 'utf8')
const tables = ['project_phase', 'project_phase_target', 'project_phase_check', 'project_review', 'project_review_metric', 'activity_daily', 'member_version_skill']
const statements = parseSchema(text).filter(s => tables.some(t => new RegExp(`^(?:CREATE TABLE ${t}\\b|CREATE (?:UNIQUE )?INDEX \\w+ ON ${t}\\b|CREATE TRIGGER \\w+[\\s\\S]*?\\bON ${t}\\b)`).test(s.text)))
const sql = statements.map(s => s.text).join('\n\n') + '\n'
const sha = createHash('sha256').update(text).digest('hex')
const content = `// Generated by node src/store/schema/generate-projects.mjs; source docs/schema-2026-11-14.sql\nexport const PROJECTS_SCHEMA_META = ${JSON.stringify({authority: 'docs/schema-2026-11-14.sql', authoritySha256: sha, tableNames: tables})} as const\nexport const PROJECTS_SCHEMA_SQL = ${JSON.stringify(sql)}\n`
const target = new URL('./003_projects.sql.ts', import.meta.url)
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== content) throw new Error('Migration 3 differs from authoritative DDL')
} else writeFileSync(target, content)
